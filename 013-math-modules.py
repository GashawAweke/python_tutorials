import math


# USEFUL MATH FUNCTIONS
# | Function | Purpose |
# | ---------------- | ----------- |
# | math.ceil() | Round up |
# | math.floor() | Round down |
# | math.sqrt() | Square root |
# | math.pow() | Power |
# | math.sin() | Sine |
# | math.cos() | Cosine |
# | math.log() | Logarithm |
# | math.factorial() | Factorial |


# Ceiling: Rounds upward.
print(math.ceil(2.2))


# Floor: Rounds downward.

print(math.floor(2.9))


# square root
print(math.sqrt(25))


# power
print(math.pow(2, 8))


# constants

print(math.pi)

print(math.e)


# factorial

print(math.factorial(3))
