# The Python Package Index(PyPI) is the official repository of Python packages.

# Think of it as:

# Python → PyPI
# Node.js → npm
# Rust → crates.io


# Examples of packages on PyPI:

# requests → HTTP requests
# numpy → numerical computing
# pandas → data analysis
# fastapi → APIs
# django → web framework


# Searching Packages
# pip search requests

# Note: pip search is deprecated.

# Instead, search directly on:

# [PyPI Search](https://pypi.org/search/?utm_source=chatgpt.com)


# Installing Packages
# pip install request


# pecific version
# pip install requests ==2.32.5

# Install a minimum version:
# pip install "requests>=2.30.0"

# Install a version range:
# pip install "requests>=2.30,<3.0"
