

# compare and return boolen


# | Operator | Meaning               | Example    | Result  |
# | -------- | --------------------- | ---------- | ------- |
# | `==`     | Equal to              | `10 == 10` | `True`  |
# | `!=`     | Not equal to          | `10 != 5`  | `True`  |
# | `>`      | Greater than          | `10 > 3`   | `True`  |
# | `<`      | Less than             | `10 < 20`  | `True`  |
# | `>=`     | Greater than or equal | `10 >= 10` | `True`  |
# | `<=`     | Less than or equal    | `10 <= 5`  | `False` |


print(10 > 3)      # True
print(10 >= 10)    # True
print(10 == 10)    # True
print(10 != 10)    # False


# comparing different types => False
print(10 == "10")  # False


#  string
print(10 == "10")  # False
